/**
 * Material You colours when the phone provides them, otherwise the app's own teal scheme ([LightColors] / [DarkColors]). Turning
 * One UI's Color palette on or off changes the configuration, so [dynamicColor] is re-checked then.
 */
@Composable
fun AmbientMusicTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = rememberMaterialYouOn(),
    content: @Composable () -> Unit,
) {
    val context = LocalContext.current
    val colorScheme = when {
        dynamicColor && darkTheme -> dynamicDarkColorScheme(context)
        dynamicColor -> dynamicLightColorScheme(context)
        darkTheme -> DarkColors
        else -> LightColors
    }

    MaterialTheme(colorScheme = colorScheme, shapes = AppShapes, content = content)
}

@Composable
private fun rememberMaterialYouOn(): Boolean {
    val context = LocalContext.current
    val configuration = LocalConfiguration.current
    return remember(configuration) { isMaterialYouOn(context) }
}
